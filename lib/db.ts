import Dexie, { type EntityTable } from "dexie";

/**
 * UUID generator that works in both secure (HTTPS) and non-secure (HTTP) contexts.
 * crypto.randomUUID() requires a secure context — unavailable on iOS/Android over HTTP.
 * The Math.random() fallback is safe for local ID generation (not cryptographic use).
 */
export function generateId(): string {
    if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
        return crypto.randomUUID();
    }
    // RFC 4122 v4 UUID fallback
    return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (c) => {
        const r = (Math.random() * 16) | 0;
        const v = c === "x" ? r : (r & 0x3) | 0x8;
        return v.toString(16);
    });
}

// ─── Local Schema Types ───────────────────────────────────────────────

export interface LocalIncident {
    /** UUID — generated by generateId() (works in HTTP + HTTPS contexts) */
    id: string;
    company_id?: string;
    reported_by_name?: string;
    reported_by_role?: string;
    event_type?: "casi_accidente" | "accidente" | "condicion_insegura";
    description?: string;
    /** base64 JPEG with GPS EXIF embedded — stored locally before upload */
    photo_blob?: string;
    photo_url?: string;
    photo_lat?: number;
    photo_lng?: number;
    photo_timestamp?: string;
    /** base64 PNG from signature canvas */
    signature_blob?: string;
    signature_url?: string;
    location_name?: string;
    /** pending | synced | error */
    sync_status: "pending" | "synced" | "error";
    created_at: string;
    updated_at: string;

    // ─── Module 2: Classification fields (DB v2) ─────────────────────────
    /** Set to 'classified' once the Module 2 wizard is completed */
    classification_status?: "pending" | "classified";

    // Worker data
    worker_name?: string;
    worker_id_number?: string;
    worker_position?: string;
    worker_eps?: string;
    worker_arl?: string;
    worker_hire_date?: string;

    // Accident classification (Res. 1401 / Ley 1562)
    severity?: "leve" | "grave" | "mortal";
    is_work_accident?: boolean;
    work_center?: string;
    accident_zone?: "dentro_empresa" | "fuera_empresa" | "en_trayecto" | "comision";
    accident_mechanism?: string;
    accident_agent?: string;
    activity_at_time?: string;

    // Injury classification (FURAT / Res. 1401)
    injury_type?: string;
    body_part_code?: string;
    body_part_description?: string;
    disability_days?: number;
    /**
     * ANSI Z16.1 charged day entry IDs.
     * Used to calculate DIAS_CARGADOS_AT in RUC/CCS export.
     * See lib/constants/ansi-charged-days.ts
     */
    charged_day_entries?: string[];

    // ─── Module 1+: Relato de los Hechos (narrative step) ────────────────────
    /** Written or transcribed description of the event by the reporter */
    reporter_description?: string;
    /** base64 webm/ogg audio recorded by the reporter */
    reporter_voice_blob?: string;
    /** Witness name (optional) */
    witness_name?: string;
    /** Witness description of what they saw */
    witness_description?: string;
    /** base64 webm/ogg audio recorded by the witness */
    witness_voice_blob?: string;
}

