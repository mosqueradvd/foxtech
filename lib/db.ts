/**
 * lib/db.ts
 * Dexie.js (IndexedDB) schema for offline-first data storage.
 * ALL form data is saved locally on every change — never blocks on network.
 */
import Dexie, { type EntityTable } from "dexie";

/**
 * UUID generator that works in both secure (HTTPS) and non-secure (HTTP) contexts.
 * crypto.randomUUID() requires a secure context — unavailable on iOS/Android over HTTP.
 * The Math.random() fallback is safe for local ID generation (not cryptographic use).
 */
export function generateId(): string {
    if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
        return crypto.randomUUID();
    }
    // RFC 4122 v4 UUID fallback
    return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (c) => {
        const r = (Math.random() * 16) | 0;
        const v = c === "x" ? r : (r & 0x3) | 0x8;
        return v.toString(16);
    });
}

// ─── Local Schema Types ───────────────────────────────────────────────

export interface LocalIncident {
    /** UUID — generated by generateId() (works in HTTP + HTTPS contexts) */
    id: string;
    company_id?: string;
    reported_by_name?: string;
    reported_by_role?: string;
    event_type?: "casi_accidente" | "accidente" | "condicion_insegura";
    description?: string;
    /** base64 JPEG with GPS EXIF embedded — stored locally before upload */
    photo_blob?: string;
    photo_url?: string;
    photo_lat?: number;
    photo_lng?: number;
    photo_timestamp?: string;
    /** base64 PNG from signature canvas */
    signature_blob?: string;
    signature_url?: string;
    location_name?: string;
    /** pending | synced | error */
    sync_status: "pending" | "synced" | "error";
    created_at: string;
    updated_at: string;
}

export interface LocalInspection {
    id: string;
    company_id?: string;
    inspector_name?: string;
    template_name?: string;
    score_percent?: number;
    items?: Array<{
        id: string;
        label: string;
        required: boolean;
        checked: boolean | null;
    }>;
    location_name?: string;
    sync_status: "pending" | "synced" | "error";
    created_at: string;
    updated_at: string;
}

// ─── Dexie Database Definition ────────────────────────────────────────

class FoxtechDB extends Dexie {
    incidents!: EntityTable<LocalIncident, "id">;
    inspections!: EntityTable<LocalInspection, "id">;

    constructor() {
        super("FoxtechDB");

        this.version(1).stores({
            incidents: "id, sync_status, created_at",
            inspections: "id, sync_status, created_at",
        });
    }
}

export const db = new FoxtechDB();

// ─── Helpers ─────────────────────────────────────────────────────────

/** Create a new blank incident draft saved immediately to IndexedDB */
export async function createIncidentDraft(): Promise<string> {
    const id = generateId();
    await db.incidents.put({
        id,
        sync_status: "pending",
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
    });
    return id;
}

/** Auto-save partial incident data — called on every keystroke/change */
export async function saveIncidentDraft(
    id: string,
    partial: Partial<LocalIncident>
): Promise<void> {
    await db.incidents.update(id, {
        ...partial,
        updated_at: new Date().toISOString(),
    });
}

/** Get all pending incidents (not yet synced to Supabase) */
export async function getPendingIncidents(): Promise<LocalIncident[]> {
    return db.incidents.where("sync_status").equals("pending").toArray();
}

/** Get all pending inspections */
export async function getPendingInspections(): Promise<LocalInspection[]> {
    return db.inspections.where("sync_status").equals("pending").toArray();
}

/** Mark an incident as synced */
export async function markIncidentSynced(id: string): Promise<void> {
    await db.incidents.update(id, {
        sync_status: "synced",
        updated_at: new Date().toISOString(),
    });
}

/** Mark an inspection as synced */
export async function markInspectionSynced(id: string): Promise<void> {
    await db.inspections.update(id, {
        sync_status: "synced",
        updated_at: new Date().toISOString(),
    });
}
