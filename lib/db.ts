// ─── Module 4: Notification Tracking ─────────────────────────────────────

export type NotificationType = "mintrabajo" | "arl" | "eps";
export type NotificationStatus = "pending" | "sent" | "filed";

export interface LocalNotification {
    id: string;
    incident_id: string;
    /** Which entity was notified */
    type: NotificationType;
    /** pending = generated but not sent, sent = sent (no filing number), filed = sent + radicado */
    status: NotificationStatus;
    /** ISO timestamp when actually sent/filed */
    sent_at?: string;
    /** Radicado / case number from Mintrabajo, ARL or EPS */
    filing_number?: string;
    /** Name of the legal representative who signed */
    signed_by?: string;
    created_at: string;
    updated_at: string;
}

// ─── Dexie Database Definition ────────────────────────────────────────

class FoxtechDB extends Dexie {
    incidents!: EntityTable<LocalIncident, "id">;
    inspections!: EntityTable<LocalInspection, "id">;
    notifications!: EntityTable<LocalNotification, "id">;

    constructor() {
        super("FoxtechDB");

        // v1: original schema
        this.version(1).stores({
            incidents: "id, sync_status, created_at",
            inspections: "id, sync_status, created_at",
        });

        // v2: add Module 2 classification fields + new indexes
        this.version(2).stores({
            incidents: "id, sync_status, created_at, classification_status, severity",
            inspections: "id, sync_status, created_at",
        });

        // v3: Module 4 — notifications table (new, backward-compatible)
        this.version(3).stores({
            incidents: "id, sync_status, created_at, classification_status, severity",
            inspections: "id, sync_status, created_at",
            notifications: "id, incident_id, type, status, created_at",
        });
    }
}

export const db = new FoxtechDB();

// ─── Helpers ─────────────────────────────────────────────────────────

/** Create a new blank incident draft saved immediately to IndexedDB */
export async function createIncidentDraft(): Promise<string> {
    const id = generateId();
    await db.incidents.put({
        id,
        sync_status: "pending",
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
    });
    return id;
}

/** Auto-save partial incident data — called on every keystroke/change */
export async function saveIncidentDraft(
    id: string,
    partial: Partial<LocalIncident>
): Promise<void> {
    await db.incidents.update(id, {
        ...partial,
        updated_at: new Date().toISOString(),
    });
}

/** Get all pending incidents (not yet synced to Supabase) */
export async function getPendingIncidents(): Promise<LocalIncident[]> {
    return db.incidents.where("sync_status").equals("pending").toArray();
}

/** Get all pending inspections */
export async function getPendingInspections(): Promise<LocalInspection[]> {
    return db.inspections.where("sync_status").equals("pending").toArray();
}

/** Mark an incident as synced */
export async function markIncidentSynced(id: string): Promise<void> {
    await db.incidents.update(id, {
        sync_status: "synced",
        updated_at: new Date().toISOString(),
    });
}

/** Mark an inspection as synced */
export async function markInspectionSynced(id: string): Promise<void> {
    await db.inspections.update(id, {
        sync_status: "synced",
        updated_at: new Date().toISOString(),
    });
}

/** Get all classified accidents (for RUC export) */
export async function getClassifiedAccidents(): Promise<LocalIncident[]> {
    return db.incidents
        .where("classification_status")
        .equals("classified")
        .toArray();
}

// ─── Notification Helpers (Module 4) ─────────────────────────────────────

/** Get all notifications for a given incident */
export async function getNotificationsForIncident(
    incidentId: string
): Promise<LocalNotification[]> {
    return db.notifications.where("incident_id").equals(incidentId).toArray();
}

/** Create or update a notification record */
export async function upsertNotification(
    notification: LocalNotification
): Promise<void> {
    await db.notifications.put(notification);
}

/** Get all grave/mortal incidents that have NOT been notified to Mintrabajo */
export async function getPendingMintrabajoCases(): Promise<LocalIncident[]> {
    const seriousIncidents = await db.incidents
        .where("severity")
        .anyOf(["grave", "mortal"])
        .toArray();

    const notifiedIds = new Set(
        (await db.notifications
            .where("type")
            .equals("mintrabajo")
            .filter((n) => n.status === "sent" || n.status === "filed")
            .toArray()
        ).map((n) => n.incident_id)
    );

    return seriousIncidents.filter((i) => !notifiedIds.has(i.id));
}
